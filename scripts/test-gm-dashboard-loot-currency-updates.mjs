import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const main=readFileSync('src/main.tsx','utf8');
const gm=readFileSync('src/GmLootManager.tsx','utf8');
const claim=readFileSync('src/ClaimLootPanel.tsx','utf8');
const card=readFileSync('src/GmDashboardCard.tsx','utf8');
const sql=readFileSync('docs/sql/qr-loot-currency-7-9-update.sql','utf8');
const claimSql=readFileSync('docs/sql/claim-qr-loot-with-currency-7-9-update.sql','utf8');
assert.match(main,/title="Crafting Recipes" initiallyOpen/,'recipe card is near top and open initially');
assert.ok(main.indexOf('title="Crafting Recipes"')<main.indexOf('title="GM Item Catalog"'),'recipe editor appears before long catalog tools');
assert.match(main,/GmCraftingManager db=\{db!\}/,'recipe component retained');
assert.equal((main.match(/<GmDashboardCard/g)||[]).length,11,'every GM card wrapped');
assert.equal((main.match(/<\/GmDashboardCard>/g)||[]).length,11,'all GM collapsibles closed');
assert.match(card,/aria-expanded=\{open\}/,'card expansion state accessible');
assert.match(card,/hidden=\{!open\}/,'cards collapse without unmounting edited forms');
assert.match(card,/setOpen\(v=>!v\)/,'clicking header toggles card');
assert.match(gm,/list_campaign_currency_definitions/,'loot editor fetches campaign denominations');
assert.match(gm,/list_gm_qr_loot_currency/,'loot editor lists current currency');
assert.match(gm,/set_qr_loot_currency/,'loot editor saves or removes currency');
assert.match(gm,/Add or Update Currency/,'currency editor visible');
assert.match(gm,/items.length===0&&lootMoney.length===0/,'currency-only containers can generate QR');
assert.match(claim,/items and\/or currency/i,'claim success mentions currency');
assert.match(sql,/enable row level security/,'loot currency table has RLS');
assert.match(sql,/app_private\.is_gm\(v_campaign\)/,'currency funding is GM-restricted');
assert.match(sql,/round\(p_amount,v_precision\)<>p_amount/,'campaign currency precision is checked');
assert.match(sql,/p_amount=0 then/,'zero amount removes denomination');
assert.match(claimSql,/app_private\.ensure_character_wallet/,'claims reuse character wallet');
assert.match(claimSql,/v_currency_rewards/,'currency claims recorded in audit data');
assert.match(claimSql,/moved:=moved\+1/,'currency-only claims count as nonempty');
console.log('PASS GM collapsibles, crafting visibility and wallet-backed QR loot currency');
