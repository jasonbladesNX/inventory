assert.doesNotMatch(ui,/className="mv-potion-slot-heading"/,'per-slot header removed');
assert.match(ui,/aria-label=\{assignment\?\.definition_id\?/,'accessible slot/use descriptions retained');
assert.match(css,/\.mv-potions-heading/,'edit aligned with title');
assert.match(css,/\.mv-potion-dialog-field/,'modal dropdown styled');
