import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const ui=readFileSync('src/CharacterScreen.tsx','utf8');
const css=readFileSync('src/character-screen.css','utf8');
const sql=readFileSync('docs/sql/character-potion-hotbar.sql','utf8');
assert.doesNotMatch(ui,/Resolved Equipment Effects/,'resolved effects card removed');
assert.match(ui,/id="mv-potions-title"/,'potions panel present');
assert.match(ui,/\[1,2,3,4\]\.map\(slot=>/,'exactly four numbered slots');
assert.match(ui,/get_character_potion_hotbar/,'hotbar state fetched on refresh');
assert.match(ui,/set_character_potion_hotbar_slot/,'slot assignment persisted');
assert.match(ui,/p_definition:definitionId\|\|null/,'empty selection clears slot');
assert.match(ui,/assignment\?\.definition_id&&!option/,'depleted potion assignment still rendered');
assert.match(ui,/candidate\.quantity/,'quantity shown in selectable option');
assert.match(ui,/usePotionSlot\(slot\)/,'one-click hotbar use');
assert.match(ui,/p_item:option\.item_id,p_quantity:1/,'use delegates to existing one-item RPC');
assert.match(ui,/await onInventoryChanged\(\)/,'refresh after consumption');
assert.match(css,/\.mv-potion-slots/,'responsive potion slot grid');
assert.match(sql,/generate_series\(1,4\)/,'database returns exactly four slots');
assert.match(sql,/security definer/,'secured hotbar functions');
assert.match(sql,/m\.user_id=\(select auth\.uid\(\)\)/,'authorized character scoping');
assert.match(sql,/d\.category='consumable' and d\.name ilike '%potion%'/,'only recognized potion definitions');
assert.match(sql,/revoke all on function public\.set_character_potion_hotbar_slot/,'anonymous writes blocked');
assert.match(sql,/jsonb_set\(coalesce\(c\.sheet_data/,'slots persist in character sheet');
console.log('PASS four-slot potion card, secured persistent assignments and one-item use contract');
