import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const combat=readFileSync('src/CombatStatusPanel.tsx','utf8');
const character=readFileSync('src/CharacterScreen.tsx','utf8');
const css=readFileSync('src/character-screen.css','utf8');
assert.match(combat,/state\.effects\.some\(entry=>entry\.kind!=='bonus'\)/,'status list only appears for conditions or nonbonus effects');
assert.match(combat,/state\.effects\.filter\(entry=>entry\.kind!=='bonus'\)/,'ability bonuses excluded from active conditions');
assert.match(combat,/entry\.group==='condition'\?'condition_remove':'effect_remove'/,'status effects remain removable');
assert.match(character,/className="mv-attribute-summary-item mv-attribute-summary-button"/,'each attribute tile is a button');
assert.match(character,/setAttributeDetailsCode\(code\)/,'attribute click selects its breakdown');
assert.match(character,/aria-haspopup="dialog"/,'attribute controls expose popup behavior');
assert.match(character,/const selectedTimedBonuses=activeTimedEffects\.filter/,'timed bonuses filtered to selected attribute');
assert.match(character,/const selectedEquipmentSources=effectSources\.filter/,'equipment sources filtered to selected attribute');
assert.match(character,/className="mv-attribute-details-summary"/,'base, effective and modifier breakdown');
assert.match(character,/selectedTimedBonuses\.map/,'duration and source listed by attribute');
assert.match(character,/selectedEquipmentSources\.map/,'equipment effect sources listed by attribute');
assert.match(character,/attributeDetailsTriggerRef\.current\?\.focus\(\)/,'closing returns focus to attribute');
assert.doesNotMatch(character,/className="mv-attribute-timed-bonus"/,'timed bonus explanation removed from card');
assert.match(css,/\.mv-attribute-summary-button:focus-visible/,'keyboard accessible attribute cards');
assert.match(css,/\.mv-attribute-details-modal/,'popup styled');
console.log('PASS condition-only status list and per-attribute bonus popups');
