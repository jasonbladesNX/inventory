import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const main=readFileSync('src/main.tsx','utf8');
const character=readFileSync('src/CharacterScreen.tsx','utf8');
const combat=readFileSync('src/CombatStatusPanel.tsx','utf8');
const sql=readFileSync('docs/sql/temporary-hp-duration-and-expiration.sql','utf8');

assert.match(main,/type Page='landing'\|'player'\|'gm-select'\|'gm'/,'GM selection screen route');
assert.match(main,/page==='gm-select'\?<section/,'GM selection page available');
assert.match(main,/aria-label="Available GM campaigns"/,'GM campaign cards displayed');
assert.match(main,/setGmCampaignIds/,'GM campaign list filtered by membership');
assert.match(main,/await loadCampaign\(c.id\);setCampaign\(c.id\);navigate\('gm'\)/,'selected campaign opens dashboard');
assert.match(character,/tempHpValue>0\?'Clear temp HP':'Temp HP'/,'temp HP action toggles label');
assert.match(character,/setTempHpOpen\(true\)/,'HP header opens temp HP popup');
assert.match(character,/p_action:'temp_hp',p_payload:\{amount:0\}/,'clear temp HP action');
assert.match(character,/tempOpen=\{tempHpOpen\}/,'temp HP dialog wired to character screen');
assert.match(combat,/tempOpen&&/,'temp HP popup rendered');
assert.match(combat,/dialog==='add'/,'one popup adds conditions and timed effects');
assert.match(combat,/kind==='condition'\?'condition_add':'effect_add'/,'combined condition and effect RPC');
assert.match(combat,/mv-combat-toolbar/,'advance time near top of character view');
assert.match(combat,/setDialog\('advance'\)/,'advance time popup');
assert.match(combat,/hpCurrent===0&&!deathDismissed/,'death saving dialog auto opens at zero HP');
assert.match(combat,/setDialog\('death'\)/,'death saves can open automatically');
assert.match(combat,/p_operation:'heal'/,'death saving dialog offers HP healing');
assert.match(combat,/setDeathDismissed\(true\)/,'closing death dialog prevents auto reopening');
assert.match(sql,/temporary_hp_duration/,'temporary HP timer persisted in sheet');
assert.match(sql,/v_duration<=0/,'temporary HP expires on matching time advancement');
assert.match(sql,/v_temp-v_absorb=0/,'temporary HP timer cleared when damage depletes protection');
console.log('PASS GM campaign picker and character modal-driven combat controls');
